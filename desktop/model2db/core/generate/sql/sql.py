"""Writes the DDL of a relational schema for one dialect: types, enums, tables, constraints and indexes, in an
order that every database accepts (a table after the tables it refers to). Mirrors web/src/core/generate/sql/sql.ts."""

import re

from ...js import is_number, js_string
from ...physical.order import order_tables
from ..todos import todo_text

# Words that would break the statement as names in at least one of the dialects
RESERVED = set(
    """
    add all alter and any as asc between by case cast check column constraint create cross current_date
    current_time current_timestamp current_user default delete desc distinct drop else end except exists false
    fetch for foreign from full grant group having in index inner insert intersect interval into is join key
    left like limit match natural not null offset on option or order outer primary range rank read references
    right row rows schema select session_user set some table then to true union unique update user using
    values when where window with
    """.split()
)

# Oracle reserves many more words, some of them usual field names (`level`, `number`, `comment`, `date`)
ORACLE_RESERVED = set(
    """
    access audit cluster column comment compress connect date decimal exclusive file float identified
    immediate increment initial integer level lock long maxextents minus mlslabel mode modify noaudit
    nocompress nowait number of offline online pctfree prior privileges public raw rename resource row rowid
    rownum rows session share size smallint start successful synonym sysdate trigger uid validate varchar
    varchar2 view whenever
    """.split()
)

# MySQL and MariaDB also reserve some usual table and column names (`lines`, `keys`, `groups`)
MYSQL_RESERVED = set(
    """
    accessible call change condition database databases delayed describe div dual each enclosed escaped exit
    explain groups high_priority infile keys kill lead lag leave lines load lock long loop low_priority mod
    modifies optimize outfile purge release rename repeat replace require restrict return revoke rlike
    separator show signal spatial sql ssl starting terminated trigger undo unlock unsigned usage use utc_date
    utc_time zerofill
    """.split()
)

_SIMPLE_NAME = re.compile(r"^[a-z_][a-z0-9_]*$")

DIALECT_NAMES = {
    "postgresql": "PostgreSQL",
    "mysql": "MySQL",
    "mariadb": "MariaDB",
    "sqlite": "SQLite",
    "sqlserver": "SQL Server",
    "oracle": "Oracle Database",
}


def _simple(name: str) -> bool:
    return _SIMPLE_NAME.match(name) is not None


def _enum_of(column_type: dict, enums: list[dict]) -> dict | None:
    if column_type["kind"] != "enum":
        return None
    return next((item for item in enums if item["name"] == column_type["name"]), None)


def _enum_width(values: list) -> int:
    """Width of a text column holding enum values: the next usual size above the longest value."""
    longest = max([1, *(len(js_string(value)) for value in values)])
    return 20 if longest <= 20 else 50 if longest <= 50 else 255


def _numeric_enum(item: dict) -> bool:
    return all(is_number(value) for value in item["values"])


def string_list(values: list) -> str:
    return ", ".join(js_string(value) if is_number(value) else "'" + value.replace("'", "''") + "'" for value in values)


def _precision(column_type: dict) -> str:
    precision = column_type.get("precision")
    scale = column_type.get("scale")
    return f"{18 if precision is None else precision}, {2 if scale is None else scale}"


class _Rules:
    identity = ""
    uuid_default = ""
    alter_foreign_keys = True
    # Several rows in one INSERT; Oracle (before 23ai) takes one statement per row
    multi_row_insert = True

    def quote(self, name: str) -> str:
        return name if _simple(name) and name not in RESERVED else '"' + name.replace('"', '""') + '"'

    def boolean(self, value: bool) -> str:
        return "1" if value else "0"

    def type(self, column_type: dict, enums: list[dict]) -> str:
        raise NotImplementedError


class _PostgreSql(_Rules):
    identity = "GENERATED BY DEFAULT AS IDENTITY"
    uuid_default = "DEFAULT gen_random_uuid()"

    def boolean(self, value: bool) -> str:
        return "TRUE" if value else "FALSE"

    def type(self, column_type: dict, enums: list[dict]) -> str:
        kind = column_type["kind"]
        if kind == "raw":
            return column_type["sql"]
        if kind == "json":
            return "JSONB"
        if kind == "array":
            return f"{self.type(column_type['items'], enums)}[]"
        if kind == "enum":
            item = _enum_of(column_type, enums)
            if not item:
                return "TEXT"
            if item["storage"] == "native":
                return self.quote(item["sqlName"])
            return "INTEGER" if _numeric_enum(item) else f"VARCHAR({_enum_width(item['values'])})"
        name, bits = column_type["name"], column_type.get("bits")
        if name == "string":
            return f"VARCHAR({column_type['length']})" if column_type.get("length") else "TEXT"
        if name == "integer":
            return "BIGINT" if bits == 64 else "SMALLINT" if bits in (8, 16) else "INTEGER"
        if name == "float":
            return "REAL" if bits == 32 else "DOUBLE PRECISION"
        if name == "decimal":
            return f"NUMERIC({_precision(column_type)})"
        return {
            "boolean": "BOOLEAN",
            "date": "DATE",
            "datetime": "TIMESTAMPTZ",
            "time": "TIME",
            "duration": "INTERVAL",
            "uuid": "UUID",
            "binary": "BYTEA",
            "any": "JSONB",
        }[name]


class _MySql(_Rules):
    identity = "AUTO_INCREMENT"
    uuid_default = "DEFAULT (UUID())"

    def quote(self, name: str) -> str:
        if _simple(name) and name not in RESERVED and name not in MYSQL_RESERVED:
            return name
        return "`" + name.replace("`", "``") + "`"

    def boolean(self, value: bool) -> str:
        return "TRUE" if value else "FALSE"

    def type(self, column_type: dict, enums: list[dict]) -> str:
        kind = column_type["kind"]
        if kind == "raw":
            return column_type["sql"]
        if kind in ("json", "array"):
            return "JSON"
        if kind == "enum":
            item = _enum_of(column_type, enums)
            if not item:
                return "VARCHAR(255)"
            if item["storage"] == "native":
                return f"ENUM({string_list([js_string(value) for value in item['values']])})"
            return "INT" if _numeric_enum(item) else f"VARCHAR({_enum_width(item['values'])})"
        name, bits = column_type["name"], column_type.get("bits")
        if name == "string":
            return f"VARCHAR({column_type['length']})" if column_type.get("length") else "TEXT"
        if name == "integer":
            return "BIGINT" if bits == 64 else "TINYINT" if bits == 8 else "SMALLINT" if bits == 16 else "INT"
        if name == "float":
            return "FLOAT" if bits == 32 else "DOUBLE"
        if name == "decimal":
            return f"DECIMAL({_precision(column_type)})"
        return {
            "boolean": "BOOLEAN",
            "date": "DATE",
            "datetime": "DATETIME(6)",
            "time": "TIME",
            "duration": "VARCHAR(50)",
            "uuid": "CHAR(36)",
            "binary": "BLOB",
            "any": "JSON",
        }[name]


class _MariaDb(_MySql):
    """MariaDB writes like MySQL, with a UUID type of its own (10.7 and later)."""

    def type(self, column_type: dict, enums: list[dict]) -> str:
        if column_type["kind"] == "primitive" and column_type["name"] == "uuid":
            return "UUID"
        return super().type(column_type, enums)


class _Sqlite(_Rules):
    # Foreign keys of a cycle are added afterwards with ALTER TABLE; SQLite cannot, and does not need to
    alter_foreign_keys = False

    def type(self, column_type: dict, enums: list[dict]) -> str:
        kind = column_type["kind"]
        if kind == "raw":
            return column_type["sql"]
        if kind in ("json", "array"):
            return "TEXT"
        if kind == "enum":
            item = _enum_of(column_type, enums)
            return "INTEGER" if item and _numeric_enum(item) else "TEXT"
        return {
            "integer": "INTEGER",
            "boolean": "INTEGER",
            "float": "REAL",
            "decimal": "NUMERIC",
            "binary": "BLOB",
        }.get(column_type["name"], "TEXT")


class _SqlServer(_Rules):
    identity = "IDENTITY(1, 1)"
    uuid_default = "DEFAULT NEWID()"

    def quote(self, name: str) -> str:
        return name if _simple(name) and name not in RESERVED else "[" + name.replace("]", "]]") + "]"

    def type(self, column_type: dict, enums: list[dict]) -> str:
        kind = column_type["kind"]
        if kind == "raw":
            return column_type["sql"]
        if kind in ("json", "array"):
            return "NVARCHAR(MAX)"
        if kind == "enum":
            item = _enum_of(column_type, enums)
            if item and _numeric_enum(item):
                return "INT"
            return f"NVARCHAR({_enum_width(item['values']) if item else 255})"
        name, bits = column_type["name"], column_type.get("bits")
        if name == "string":
            return f"NVARCHAR({column_type['length']})" if column_type.get("length") else "NVARCHAR(MAX)"
        if name == "integer":
            return "BIGINT" if bits == 64 else "TINYINT" if bits == 8 else "SMALLINT" if bits == 16 else "INT"
        if name == "float":
            return "REAL" if bits == 32 else "FLOAT"
        if name == "decimal":
            return f"DECIMAL({_precision(column_type)})"
        return {
            "boolean": "BIT",
            "date": "DATE",
            "datetime": "DATETIMEOFFSET",
            "time": "TIME",
            "duration": "NVARCHAR(50)",
            "uuid": "UNIQUEIDENTIFIER",
            "binary": "VARBINARY(MAX)",
            "any": "NVARCHAR(MAX)",
        }[name]


class _Oracle(_Rules):
    identity = "GENERATED BY DEFAULT AS IDENTITY"
    uuid_default = "DEFAULT SYS_GUID()"
    multi_row_insert = False

    def quote(self, name: str) -> str:
        if _simple(name) and name not in RESERVED and name not in ORACLE_RESERVED:
            return name
        return '"' + name.replace('"', '""') + '"'

    def type(self, column_type: dict, enums: list[dict]) -> str:
        kind = column_type["kind"]
        if kind == "raw":
            return column_type["sql"]
        if kind in ("json", "array"):
            return "JSON"
        if kind == "enum":
            item = _enum_of(column_type, enums)
            if item and _numeric_enum(item):
                return "NUMBER(10)"
            return f"VARCHAR2({_enum_width(item['values']) if item else 255} CHAR)"
        name, bits = column_type["name"], column_type.get("bits")
        if name == "string":
            length = column_type.get("length")
            return f"VARCHAR2({length} CHAR)" if length and length <= 4000 else "CLOB"
        if name == "integer":
            return (
                "NUMBER(19)"
                if bits == 64
                else "NUMBER(3)"
                if bits == 8
                else "NUMBER(5)"
                if bits == 16
                else "NUMBER(10)"
            )
        if name == "float":
            return "BINARY_FLOAT" if bits == 32 else "BINARY_DOUBLE"
        if name == "decimal":
            return f"NUMBER({_precision(column_type)})"
        return {
            "boolean": "NUMBER(1)",
            "date": "DATE",
            "datetime": "TIMESTAMP WITH TIME ZONE",
            "time": "VARCHAR2(15 CHAR)",
            "duration": "INTERVAL DAY TO SECOND",
            "uuid": "RAW(16)",
            "binary": "BLOB",
            "any": "JSON",
        }[name]


RULES = {
    "postgresql": _PostgreSql(),
    "mysql": _MySql(),
    "mariadb": _MariaDb(),
    "sqlite": _Sqlite(),
    "sqlserver": _SqlServer(),
    "oracle": _Oracle(),
}


def sql_column_type(column_type: dict, dialect: str, enums: list[dict]) -> str:
    """The database type of a column in a dialect (`VARCHAR(20)`), for writers that state it next to the code."""
    return RULES[dialect].type(column_type, enums)


def _literal(value, column: dict, rules: _Rules, enums: list[dict]) -> str | None:
    if value is None:
        return None
    if isinstance(value, bool):
        return rules.boolean(value)
    if is_number(value):
        return js_string(value)
    item = _enum_of(column["type"], enums)
    # An enum default may be written with the member's name (`ACTIVE`) while the column stores its value
    stored = value
    if item:
        stored = next(
            (candidate for candidate in item["values"] if js_string(candidate).lower() == value.lower()), value
        )
    return js_string(stored) if is_number(stored) else "'" + stored.replace("'", "''") + "'"


def generate_sql(schema: dict, dialect: str, title: str | None = None) -> str:
    rules = RULES[dialect]
    q = rules.quote
    out: list[str] = []
    out.append(f"-- {DIALECT_NAMES[dialect]} schema written by Model2DB{f' from {title}' if title else ''}.")
    out.append("-- Review it before running it: nothing here has been run.")
    if dialect == "sqlite":
        out.extend(["", "PRAGMA foreign_keys = ON;"])

    for item in schema["enums"]:
        if item["storage"] != "native" or dialect != "postgresql":
            continue
        values = string_list([js_string(value) for value in item["values"]])
        out.extend(["", f"CREATE TYPE {q(item['sqlName'])} AS ENUM ({values});"])

    tables, deferred = order_tables(schema["tables"])
    later: list[str] = []
    for table in tables:
        lines: list[str] = []
        key_column = (
            next((column for column in table["columns"] if column["name"] == table["primaryKey"][0]), None)
            if table["primaryKey"]
            else None
        )
        inline_key = (
            dialect == "sqlite"
            and len(table["primaryKey"]) == 1
            and key_column is not None
            and key_column.get("generated") == "identity"
        )
        for column in table["columns"]:
            parts = [q(column["name"]), rules.type(column["type"], schema["enums"])]
            if inline_key and column["name"] == table["primaryKey"][0]:
                lines.append(f"{q(column['name'])} INTEGER PRIMARY KEY")
                continue
            generated = column.get("generated")
            # Default and identity before NOT NULL: Oracle requires that order and the others accept it
            if generated == "identity" and rules.identity:
                parts.append(rules.identity)
            if generated == "uuid" and rules.uuid_default:
                parts.append(rules.uuid_default)
            # MySQL wants the default of a DATETIME(6) with the same precision
            if generated == "now":
                parts.append(
                    "DEFAULT CURRENT_TIMESTAMP(6)" if dialect in ("mysql", "mariadb") else "DEFAULT CURRENT_TIMESTAMP"
                )
            if "defaultValue" in column:
                value = _literal(column["defaultValue"], column, rules, schema["enums"])
                if value is not None:
                    parts.append(f"DEFAULT {value}")
            if not column["nullable"]:
                parts.append("NOT NULL")
            lines.append(" ".join(parts))
        if table["primaryKey"] and not inline_key:
            columns = ", ".join(q(name) for name in table["primaryKey"])
            lines.append(f"CONSTRAINT {q('pk_' + table['name'])} PRIMARY KEY ({columns})")
        for unique in table["uniques"]:
            lines.append(f"CONSTRAINT {q(unique['name'])} UNIQUE ({', '.join(q(name) for name in unique['columns'])})")
        postponed = deferred.get(table["name"], []) if rules.alter_foreign_keys else []
        for fk in table["foreignKeys"]:
            if any(fk is other for other in postponed):
                continue
            lines.append(_foreign_key_clause(fk, q))
        for check in table["checks"]:
            lines.append(
                f"CONSTRAINT {q(check['name'])} CHECK ({q(check['column'])} IN ({string_list(check['values'])}))"
            )

        out.append("")
        for todo in table["todos"]:
            out.append(f"-- {todo_text(todo, table['model'], 'table')}")
        body = "\n".join(f"  {line}{',' if i < len(lines) - 1 else ''}" for i, line in enumerate(lines))
        out.extend([f"CREATE TABLE {q(table['name'])} (", body, ");"])
        if table["kind"] == "lookup":
            enum_item = next((item for item in schema["enums"] if item["sqlName"] == table["name"]), None)
            insert = f"INSERT INTO {q(table['name'])} ({q(table['columns'][0]['name'])}) VALUES"
            if enum_item and rules.multi_row_insert:
                rows = ", ".join(f"({string_list([value])})" for value in enum_item["values"])
                out.append(f"{insert} {rows};")
            elif enum_item:
                for value in enum_item["values"]:
                    out.append(f"{insert} ({string_list([value])});")
        for index in table["indexes"]:
            unique = "UNIQUE " if index["unique"] else ""
            columns = ", ".join(q(name) for name in index["columns"])
            out.append(f"CREATE {unique}INDEX {q(index['name'])} ON {q(table['name'])} ({columns});")
        for fk in postponed:
            later.append(f"ALTER TABLE {q(table['name'])} ADD {_foreign_key_clause(fk, q)};")
    if later:
        out.extend(["", "-- References between tables that refer to each other", *later])
    return "\n".join(out) + "\n"


def _foreign_key_clause(fk: dict, q) -> str:
    action = f" ON DELETE {fk['onDelete'].upper()}" if fk.get("onDelete") else ""
    columns = ", ".join(q(name) for name in fk["columns"])
    references = ", ".join(q(name) for name in fk["references"])
    return f"CONSTRAINT {q(fk['name'])} FOREIGN KEY ({columns}) REFERENCES {q(fk['table'])} ({references}){action}"
