CREATE TABLE users (
  id VARCHAR2(255 CHAR) NOT NULL,
  email VARCHAR2(255 CHAR) NOT NULL,
  name VARCHAR2(255 CHAR),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  profile_bio VARCHAR2(255 CHAR),
  profile_website VARCHAR2(255 CHAR),
  CONSTRAINT pk_users PRIMARY KEY (id),
  CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE posts (
  id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  title VARCHAR2(200 CHAR) NOT NULL,
  body VARCHAR2(255 CHAR) NOT NULL,
  published NUMBER(1) DEFAULT 0 NOT NULL,
  author_id VARCHAR2(255 CHAR) NOT NULL,
  CONSTRAINT pk_posts PRIMARY KEY (id),
  CONSTRAINT fk_posts_author_id FOREIGN KEY (author_id) REFERENCES users (id)
);
CREATE INDEX ix_posts_author_id ON posts (author_id);

CREATE TABLE comments (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  text VARCHAR2(255 CHAR) NOT NULL,
  written_at TIMESTAMP WITH TIME ZONE NOT NULL,
  rating NUMBER(10),
  post_id NUMBER(10) NOT NULL,
  CONSTRAINT pk_comments PRIMARY KEY (id),
  CONSTRAINT fk_comments_post_id FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE
);
CREATE INDEX ix_comments_post_id ON comments (post_id);

CREATE TABLE post_tags (
  post_id NUMBER(10) NOT NULL,
  position NUMBER(10) NOT NULL,
  value VARCHAR2(255 CHAR) NOT NULL,
  CONSTRAINT pk_post_tags PRIMARY KEY (post_id, position),
  CONSTRAINT fk_post_tags_post_id FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE
);
